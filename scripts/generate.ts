// Builds every derived file from the two schema inputs:
//
//   schema/source-rules.json  facts extracted from the official source code
//                             (scripts/extract-schema.mjs)
//   schema/attributes.json    curated attribute specification, checked
//                             against source-rules.json by the tests
//
// Outputs:
//   schema/statement-schema.json          the published, resolved schema
//   python/src/rationale/schema.json      the same file for the Python package
//   openapi/transparency-database.openapi.json
//   src/generated/schema.ts               the schema as a typed constant
//   src/generated/openapi-types.ts        TypeScript types derived from the OpenAPI document
//
// Run `node scripts/generate.ts` to write them, `--check` to only compare.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = Record<string, Json>;

const HEADER_TS = '/*\n * Copyright 2026 MB AFKzona Group\n * SPDX-License-Identifier: Apache-2.0\n */\n\n// Generated by scripts/generate.ts. Do not edit by hand.\n';
const DOCUMENTATION_URL = 'https://transparency.dsa.ec.europa.eu/page/api-documentation';
const PRODUCTION_BASE_URL = 'https://transparency.dsa.ec.europa.eu';

function obj(v: Json | undefined, what: string): JsonObject {
  if (v === null || typeof v !== 'object' || Array.isArray(v)) throw new Error(`${what} is not an object`);
  return v;
}
function str(v: Json | undefined, what: string): string {
  if (typeof v !== 'string') throw new Error(`${what} is not a string`);
  return v;
}
function strArray(v: Json | undefined, what: string): string[] {
  if (!Array.isArray(v) || !v.every((x) => typeof x === 'string')) throw new Error(`${what} is not a string array`);
  return v.filter((x): x is string => typeof x === 'string');
}

/** Resolves an enumeration reference such as "Statement::KEYWORDS" to its values and labels. */
function resolveEnum(rules: JsonObject, ref: string, source: string): { values: string[]; labels?: Record<string, string> } {
  const [cls, name] = ref.split('::');
  if (!cls || !name) throw new Error(`bad enum reference ${ref}`);
  if (cls === 'Statement') {
    const e = obj(rules['enums'], 'enums')[name];
    if (Array.isArray(e)) return { values: strArray(e, ref) };
    const map = obj(e, ref);
    const labels = Object.fromEntries(Object.entries(map).map(([k, v]) => [k, str(v, ref)]));
    return source === 'keys' ? { values: Object.keys(labels), labels } : { values: Object.values(labels) };
  }
  return { values: strArray(obj(rules['lists'], 'lists')[ref], ref) };
}

/** The resolved, published schema. */
export function buildSchema(rules: JsonObject, attrs: JsonObject): JsonObject {
  const source = obj(rules['source'], 'source');
  const commit = str(source['commit'], 'commit');
  const effective = str(attrs['schemaEffective'], 'schemaEffective');
  const attributes: JsonObject = {};
  for (const [name, specJson] of Object.entries(obj(attrs['attributes'], 'attributes'))) {
    const spec = { ...obj(specJson, name) };
    if (typeof spec['enum'] === 'string') {
      const { values, labels } = resolveEnum(rules, spec['enum'], str(spec['enumSource'], `${name}.enumSource`));
      spec['values'] = values;
      if (labels) spec['labels'] = labels;
    }
    attributes[name] = spec;
  }
  const lists = obj(rules['lists'], 'lists');
  const endpoints = (rules['endpoints'] as JsonObject[]).map((e) => ({ method: str(e['method'], 'method'), path: str(e['path'], 'path') }));
  const find = (method: string, path: string): string => {
    const hit = endpoints.find((e) => e.method === method && (e.path === path || (path.endsWith('/') && e.path.startsWith(path))));
    if (!hit) throw new Error(`endpoint ${method} ${path} not in source rules`);
    return hit.path;
  };
  return {
    $comment: 'Statement of reasons schema of the DSA Transparency Database API, resolved by scripts/generate.ts from schema/source-rules.json and schema/attributes.json. Do not edit by hand.',
    schemaVersion: `${effective}+${commit.slice(0, 8)}`,
    schemaEffective: effective,
    source: {
      repository: str(source['repository'], 'repository'),
      commit,
      fetched: str(source['fetched'], 'fetched'),
      documentation: DOCUMENTATION_URL,
      files: source['files'] ?? null,
    },
    api: {
      productionBaseUrl: PRODUCTION_BASE_URL,
      single: find('POST', '/api/v1/statement'),
      batch: find('POST', '/api/v1/statements'),
      existingPuid: find('GET', '/api/v1/statement/existing-puid/'),
      batchSize: rules['batch'] ?? null,
      rateLimits: rules['rateLimits'] ?? null,
      // Seconds the server holds its per-PUID lock while it stores a statement.
      puidLockSeconds: obj(rules['puid'], 'puid')['lockSeconds'] ?? null,
    },
    trim: obj(attrs['trim'], 'trim')['codePoints'] ?? null,
    decisionGroup: attrs['decisionGroup'] ?? null,
    territorialPresets: {
      EU: lists['EuropeanCountriesService::EUROPEAN_UNION_COUNTRY_CODES'] ?? null,
      EEA: lists['EuropeanCountriesService::EUROPEAN_ECONOMIC_AREA_COUNTRY_CODES'] ?? null,
    },
    attributes,
    notAccepted: attrs['notAccepted'] ?? null,
  };
}

/** An OpenAPI 3.1 description of the submission endpoints, derived from the schema. */
export function buildOpenApi(schema: JsonObject): JsonObject {
  const attributes = obj(schema['attributes'], 'attributes');
  const api = obj(schema['api'], 'api');
  const batchSize = obj(api['batchSize'], 'batchSize');
  const properties: JsonObject = {};
  const required: string[] = [];
  for (const [name, specJson] of Object.entries(attributes)) {
    const spec = obj(specJson, name);
    const description = str(spec['label'], `${name}.label`);
    let p: JsonObject;
    switch (spec['kind']) {
      case 'text':
        p = { type: 'string', maxLength: spec['max'] ?? null, description };
        if (typeof spec['pattern'] === 'string') p['pattern'] = spec['pattern'];
        break;
      case 'url':
        p = { type: 'string', format: 'uri', maxLength: spec['max'] ?? null, description };
        break;
      case 'date':
        p = { type: 'string', format: 'date', description };
        break;
      case 'enum':
        p = { type: 'string', enum: spec['values'] ?? null, description };
        break;
      case 'enum-list':
        p = { type: 'array', items: { type: 'string', enum: spec['values'] ?? null }, description };
        break;
      case 'content-id': {
        const keys = obj(spec['keys'], `${name}.keys`);
        p = {
          type: 'object',
          additionalProperties: false,
          properties: Object.fromEntries(Object.entries(keys).map(([k, v]) => [k, { type: 'string', pattern: str(obj(v, k)['pattern'], k) }])),
          description,
        };
        break;
      }
      default:
        throw new Error(`unknown kind for ${name}`);
    }
    properties[name] = p;
    if (spec['required'] === true) required.push(name);
  }
  const statement: JsonObject = { type: 'object', additionalProperties: false, required, properties };
  const created: JsonObject = {
    type: 'object',
    required: ['uuid', 'puid'],
    properties: {
      uuid: { type: 'string', format: 'uuid' },
      puid: { type: 'string' },
      created_at: { type: 'string' },
      permalink: { type: 'string' },
      self: { type: 'string' },
      platform_name: { type: 'string' },
    },
  };
  const errorBody: JsonObject = {
    type: 'object',
    properties: {
      message: { type: 'string' },
      errors: { type: 'object', additionalProperties: true },
      existing: { type: 'object', properties: { puid: { type: 'string' } } },
    },
  };
  const json = (schemaRef: string): JsonObject => ({ 'application/json': { schema: { $ref: `#/components/schemas/${schemaRef}` } } });
  const security: Json = [{ bearer: [] }];
  return {
    openapi: '3.1.0',
    info: {
      title: 'DSA Transparency Database: statement of reasons submission (unofficial description)',
      version: str(schema['schemaVersion'], 'schemaVersion'),
      description: `Derived by Rationale from the official source code (${str(obj(schema['source'], 'source')['repository'], 'repository')} at ${str(obj(schema['source'], 'source')['commit'], 'commit')}) and the API documentation (${DOCUMENTATION_URL}). The Commission does not publish an OpenAPI document; this file is not official.`,
    },
    servers: [{ url: str(api['productionBaseUrl'], 'productionBaseUrl'), description: 'Production. The sandbox host is given to each platform during onboarding.' }],
    components: {
      securitySchemes: { bearer: { type: 'http', scheme: 'bearer' } },
      schemas: {
        Statement: statement,
        StatementCreated: created,
        StatementBatch: { type: 'object', required: ['statements'], properties: { statements: { type: 'array', minItems: batchSize['min'] ?? null, maxItems: batchSize['max'] ?? null, items: { $ref: '#/components/schemas/Statement' } } } },
        StatementBatchCreated: { type: 'object', required: ['statements'], properties: { statements: { type: 'array', items: { $ref: '#/components/schemas/StatementCreated' } } } },
        ErrorBody: errorBody,
        PuidLookup: { type: 'object', properties: { message: { type: 'string' }, puid: { type: 'string' } } },
      },
    },
    paths: {
      [str(api['single'], 'single')]: {
        post: {
          operationId: 'createStatement',
          security,
          requestBody: { required: true, content: json('Statement') },
          responses: { '201': { description: 'Created', content: json('StatementCreated') }, '401': { description: 'Unauthenticated' }, '422': { description: 'Validation error or PUID not unique', content: json('ErrorBody') }, '429': { description: 'Rate limit reached' } },
        },
      },
      [str(api['batch'], 'batch')]: {
        post: {
          operationId: 'createStatements',
          security,
          requestBody: { required: true, content: json('StatementBatch') },
          responses: { '201': { description: 'Created', content: json('StatementBatchCreated') }, '401': { description: 'Unauthenticated' }, '422': { description: 'Validation error (errors.statement_N) or PUIDs not unique (errors.existing_puids); nothing was created', content: json('ErrorBody') }, '429': { description: 'Rate limit reached' } },
        },
      },
      [str(api['existingPuid'], 'existingPuid')]: {
        get: {
          operationId: 'existingPuid',
          security,
          parameters: [{ name: 'puid', in: 'path', required: true, schema: { type: 'string' } }],
          responses: { '302': { description: 'A statement with this PUID exists', content: json('PuidLookup') }, '404': { description: 'No statement with this PUID', content: json('PuidLookup') } },
        },
      },
    },
  };
}

function tsName(name: string): string {
  return name
    .split(/[_-]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

/** Converts one OpenAPI schema object to a TypeScript type expression. */
function tsType(s: JsonObject, indent: string): string {
  if (typeof s['$ref'] === 'string') return s['$ref'].split('/').pop() ?? 'unknown';
  if (Array.isArray(s['enum'])) return s['enum'].map((v) => JSON.stringify(v)).join(' | ');
  switch (s['type']) {
    case 'string':
      return 'string';
    case 'array':
      return `readonly (${tsType(obj(s['items'], 'items'), indent)})[]`;
    case 'object': {
      const props = s['properties'] ? obj(s['properties'], 'properties') : {};
      const req = new Set(Array.isArray(s['required']) ? (s['required'] as string[]) : []);
      const lines = Object.entries(props).map(([k, v]) => {
        const p = obj(v, k);
        const doc = typeof p['description'] === 'string' ? `${indent}  /** ${p['description']}. */\n` : '';
        const key = /^[a-z_][a-z0-9_]*$/i.test(k) ? k : JSON.stringify(k);
        return `${doc}${indent}  readonly ${key}${req.has(k) ? '' : '?'}: ${tsType(p, `${indent}  `)};`;
      });
      if (lines.length === 0 && s['additionalProperties'] === true) return 'Readonly<Record<string, unknown>>';
      const body = `{\n${lines.join('\n')}\n${indent}}`;
      return s['additionalProperties'] === true ? `${body} & Readonly<Record<string, unknown>>` : body;
    }
    default:
      return 'unknown';
  }
}

/** TypeScript types derived from the OpenAPI document. */
export function buildOpenApiTypes(openapi: JsonObject): string {
  const schemas = obj(obj(openapi['components'], 'components')['schemas'], 'schemas');
  const out: string[] = [HEADER_TS, '// Source: openapi/transparency-database.openapi.json\n'];
  const statement = obj(schemas['Statement'], 'Statement');
  for (const [name, v] of Object.entries(obj(statement['properties'], 'properties'))) {
    const p = obj(v, name);
    const enumSource = Array.isArray(p['enum']) ? p : p['items'] && Array.isArray(obj(p['items'], 'items')['enum']) ? obj(p['items'], 'items') : null;
    if (enumSource) out.push(`/** Allowed values of \`${name}\`. */\nexport type ${tsName(name)}Value = ${tsType({ enum: enumSource['enum'] ?? null }, '')};\n`);
  }
  for (const [name, v] of Object.entries(schemas)) {
    out.push(`/** OpenAPI schema \`${name}\`. */\nexport interface ${name} ${tsType(obj(v, name), '')}\n`);
  }
  return out.join('\n');
}

/** The schema as a typed TypeScript constant. */
export function buildSchemaModule(schema: JsonObject): string {
  return `${HEADER_TS}\n/** The resolved statement of reasons schema (see schema/statement-schema.json). */\nexport const SCHEMA = ${asciiJson(schema, 2)} as const;\n`;
}

/** JSON text with every character outside printable ASCII escaped, so generated files hold no invisible characters. */
export function asciiJson(value: unknown, indent: number): string {
  return JSON.stringify(value, null, indent).replace(/[^\x20-\x7e\n]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

/** Every generated file, keyed by its path relative to the repository root. */
export function buildAll(root: string): Record<string, string> {
  const read = (p: string): JsonObject => obj(JSON.parse(readFileSync(join(root, p), 'utf8')) as Json, p);
  const schema = buildSchema(read('schema/source-rules.json'), read('schema/attributes.json'));
  const openapi = buildOpenApi(schema);
  const schemaJson = `${asciiJson(schema, 2)}\n`;
  return {
    'schema/statement-schema.json': schemaJson,
    'python/src/rationale/schema.json': schemaJson,
    'openapi/transparency-database.openapi.json': `${asciiJson(openapi, 2)}\n`,
    'src/generated/schema.ts': buildSchemaModule(schema),
    'src/generated/openapi-types.ts': buildOpenApiTypes(openapi),
  };
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, content] of Object.entries(buildAll(root))) {
    const target = join(root, rel);
    let current: string;
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      current = '';
    }
    if (current === content) continue;
    if (check) {
      console.error(`stale: ${rel}`);
      stale++;
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
      console.error(`wrote ${rel}`);
    }
  }
  if (stale > 0) process.exit(1);
}
